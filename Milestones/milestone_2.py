#Q10

def map_score(actual, preds):
    if actual in preds:
        rank = preds.index(actual) + 1
        return 1 / rank
    return 0

combined_texts = []

for row in train_ds:
    full_text = (
        row["prompt"] + " " +
        row["A"] + " " +
        row["B"] + " " +
        row["C"] + " " +
        row["D"] + " " +
        row["E"]
    )
    combined_texts.append(full_text)

vectorizer = TfidfVectorizer(stop_words="english")
vectorizer.fit(combined_texts)

labels = ["A", "B", "C", "D", "E"]

tfidf_top3 = []
tfidf_map_scores = []

for row in train_ds:
    prompt_vec = vectorizer.transform([row["prompt"]])

    scores = []

    for label in labels:
        option_vec = vectorizer.transform([row[label]])
        sim = cosine_similarity(prompt_vec, option_vec)[0][0]
        scores.append((label, sim))

    scores.sort(key=lambda x: x[1], reverse=True)

    top3 = [scores[0][0], scores[1][0], scores[2][0]]
    tfidf_top3.append(top3)

    tfidf_map_scores.append(
        map_score(row["answer"], top3)
    )

#Pipeline-2
minilm_top3 = []
minilm_map_scores = []

for row in train_ds:

    prompt_emb = st_model.encode(
        row["prompt"],
        convert_to_tensor=True
    )

    scores = []

    for label in labels:
        option_emb = st_model.encode(
            row[label],
            convert_to_tensor=True
        )

        sim = util.cos_sim(prompt_emb, option_emb).item()
        scores.append((label, sim))

    scores.sort(key=lambda x: x[1], reverse=True)

    top3 = [scores[0][0], scores[1][0], scores[2][0]]
    minilm_top3.append(top3)

    minilm_map_scores.append(
        map_score(row["answer"], top3)
    )

print(np.mean(minilm_map_scores))

count = 0

for i, row in enumerate(train_ds):
    answer = row["answer"]

    if answer not in tfidf_top3[i] and answer in minilm_top3[i]:
        count += 1

print(count)

